import hashlib, json
from pathlib import Path
base=Path(r'D:\en-words\review\ladder-integrated-browser-acceptance-20261016')
manifest=json.loads((base/'evidence'/'formal-before.json').read_text(encoding='utf-8-sig'))['formal_node_modules']
root=base/'source'/'web'/'node_modules'
current={}
for p in root.rglob('*'):
    if p.is_file() and '.vite' not in p.relative_to(root).parts:
        rel=p.relative_to(root).as_posix()
        h=hashlib.sha256()
        with p.open('rb') as f:
            for b in iter(lambda:f.read(1024*1024),b''): h.update(b)
        current[rel]={'sha256':h.hexdigest(),'bytes':p.stat().st_size}
diffs=[]
for k in sorted(set(manifest)|set(current)):
    a,b=manifest.get(k),current.get(k)
    if a!=b: diffs.append({'path':k,'old':a,'new':b,'kind':'added' if a is None else 'missing' if b is None else 'changed'})
out={'baseline_files':len(manifest),'current_files':len(current),'baseline_bytes':sum(v['bytes'] for v in manifest.values()),'current_bytes':sum(v['bytes'] for v in current.values()),'diff_count':len(diffs),'diffs':diffs}
print(json.dumps(out,ensure_ascii=False,indent=2))
